#include "stm32f10x.h"
#include "dht11.h"
#include "bh1750.h"
#include "uart.h"
#include "tim.h"
#include "control.h"
#include <stdio.h>

/* ---- 传感器数据（control.c通过extern访问） ---- */
volatile float   g_temp = 0;
volatile uint8_t g_humi = 0;
volatile float   g_lux  = 0;

/* ---- SysTick毫秒计数（control.c通过extern访问） ---- */
volatile uint32_t g_tick_ms = 0;

void SysTick_Handler(void) {
    g_tick_ms++;
}

int main(void) {
    char    txbuf[64];
    uint8_t raw_temp = 0, raw_humi = 0;

    /* SysTick配置为1ms中断（72MHz） */
    SysTick_Config(SystemCoreClock / 1000);

    /* 各模块初始化 */
    UART1_Init();
    BH1750_Init();
    DHT11_Init();
    TIM2_Init();
    TIM1_PWM_Init();
    Control_Init();

    /* 等待传感器上电稳定 */
    for (volatile uint32_t d = 0; d < 2000; d++) {
        /* 等约2秒（SysTick已启动可用delay，这里简单循环） */
        for (volatile uint32_t e = 0; e < 72000; e++) __NOP();
    }

    while (1) {
        /* ================================================
           1. 每分钟采样 + 上报 + 更新PID
           ================================================ */
        if (g_sample_flag) {
            g_sample_flag = 0;

            /* 读DHT11（失败则保留上次值） */
            if (DHT11_Read(&raw_temp, &raw_humi)) {
                g_temp = (float)raw_temp;
                g_humi = raw_humi;
            }

            /* 读BH1750 */
            g_lux = BH1750_Read();

            /* 拼包发送给ESP8266，格式：SENSOR:25,68,100.0\n */
            snprintf(txbuf, sizeof(txbuf),
                     "SENSOR:%d,%d,%.1f\n",
                     (int)g_temp, (int)g_humi, g_lux);
            UART1_Send(txbuf);

            /* 采样完成后执行一次PID计算更新热床功率 */
            Control_HeaterPID();
        }

        /* ================================================
           2. 处理ESP8266下发的CMD
           ================================================ */
        if (g_rx_ready) {
            g_rx_ready = 0;
            UART1_ParseCMD();
            /* PID目标值已在ParseCMD中更新g_target_temp/humid */
        }

        /* ================================================
           3. 水泵软PWM（高频轮询，10ms级响应）
           ================================================ */
        Control_PumpUpdate();

        /* ================================================
           4. 蜂鸣器超限报警（持续监测）
           ================================================ */
        Control_AlarmUpdate();
    }
}
